import {test,expect} from '@playwright/test';
test('parent selection persists and restricts online and offline letter practice',async({page})=>{
  await page.goto('/');
  expect((await page.request.get('/api/parent/letters')).status()).toBe(403);
  await page.getByRole('button',{name:'Szülőknek',exact:true}).click();
  await expect(page.locator('.challenge')).toContainText('×');
  const numbers=(await page.locator('.challenge').innerText()).match(/\d+/g).map(Number);
  await page.locator('#parent-answer').fill(String(numbers[0]*numbers[1]));
  await page.getByRole('button',{name:'Megnézem a haladást'}).click();
  await expect(page.locator('.letter-settings')).toBeVisible();
  await page.getByRole('button',{name:'Kijelölés törlése',exact:true}).click();
  await page.getByRole('button',{name:'Betűk mentése',exact:true}).click();
  await expect(page.locator('.letter-save-message')).toContainText('legalább egy');
  await page.locator('.parent-letters input[value="A"]').check();
  await page.getByRole('button',{name:'Betűk mentése',exact:true}).click();
  await expect(page.locator('.letter-save-message')).toContainText('Mentve!');
  expect((await(await page.request.get('/api/parent/letters')).json()).letters).toEqual(['A']);
  const otherDevice = await page.context().browser().newContext();
  try {
    const current = await (await otherDevice.request.get('http://127.0.0.1:8080/api/child/current')).json();
    expect(current.child).toBeNull();expect(current.practiceLetters).toEqual(['A']);
    await otherDevice.request.post('http://127.0.0.1:8080/api/sessions',{data:{},headers:{'X-CSRF-Token':current.csrfToken}});
    const fresh = await (await otherDevice.request.get('http://127.0.0.1:8080/api/exercises/next?module=clouds')).json();
    expect(fresh.target).toBe('A');expect(fresh.choices.every(choice=>choice.value==='A')).toBe(true);
  } finally { await otherDevice.close(); }
  const csrf=(await(await page.request.get('/api/child/current')).json()).csrfToken;
  for(const letters of [[],['?']]) expect((await page.request.put('/api/parent/letters',{data:{letters},headers:{'X-CSRF-Token':csrf}})).status()).toBe(422);
  const cloud=await(await page.request.get('/api/exercises/next?module=clouds')).json();
  expect(cloud.serverIssued).toBe(true);expect(cloud.target).toBe('A');expect(cloud.choices.every(choice=>choice.value==='A')).toBe(true);
  expect((await page.request.get('/api/exercises/next?module=writing&index=2')).status()).toBe(422);
  await page.getByRole('button',{name:'Vissza az erdei világba'}).click();
  await page.locator('[data-place="clouds"]').click();
  await expect(page.locator('.activity')).toHaveAttribute('aria-busy','false');
  await expect(page.locator('.letter-cloud')).toHaveText(['A']);
  await page.getByRole('button',{name:'Vissza az erdei világba'}).click();
  await page.locator('[data-place="writing"]').click();
  await expect(page.locator('.activity')).toHaveAttribute('aria-busy','false');
  await expect(page.locator('.trace-picker button')).toHaveText(['A','a']);
  await page.getByRole('button',{name:'Vissza az erdei világba'}).click();
  await page.locator('[data-place="words"]').click();
  await expect(page.locator('.activity')).toHaveAttribute('aria-busy','false');
  await expect(page.locator('.word-tile')).toHaveText(['A']);
  await page.getByRole('button',{name:'🧩 Kirakás',exact:true}).click();
  await expect(page.locator('.feedback')).toContainText('még nincs feladat');
  await page.reload();
  await page.locator('[data-place="clouds"]').click();
  await expect(page.locator('.activity')).toHaveAttribute('aria-busy','false');
  await expect(page.locator('.letter-cloud')).toHaveText(['A']);
  await page.getByRole('button',{name:'Vissza az erdei világba'}).click();
  await page.context().setOffline(true);
  await page.locator('[data-place="clouds"]').click();
  await expect(page.locator('.letter-cloud')).toHaveText(['A']);
  await page.getByRole('button',{name:'Vissza az erdei világba'}).click();
  await page.locator('[data-place="reading"]').click();
  await expect(page.locator('.feedback')).toContainText('még nincs olvasnivaló');
});
